-- 43-hub-postgres 43b: PostgreSQL schema (mirrors SQLite schema in packages/hub/src/db.ts).
-- Types: SQLite INTEGER (ms epoch ids/timestamps) -> bigint; TEXT -> text; REAL -> double precision;
--        0/1 booleans -> smallint.  usage_daily is range-partitioned on date (monthly managed in 43d),
--        with a DEFAULT partition so writes always succeed; its surrogate `id` is dropped in favour of
--        the natural PK (user_id, host_id, date, instance_id) which the partition key requires.

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL,
  password_hash text NOT NULL,
  ver integer NOT NULL DEFAULT 1,
  created_at text NOT NULL,
  must_change smallint NOT NULL DEFAULT 0,
  email text,
  email_verified smallint NOT NULL DEFAULT 0,
  totp_secret text,
  failed_attempts integer NOT NULL DEFAULT 0,
  locked_until bigint,
  phone text,
  phone_verified smallint NOT NULL DEFAULT 0,
  account_status text NOT NULL DEFAULT 'active',
  role text NOT NULL DEFAULT 'user',
  plan_status text,
  plan_expires_at bigint,
  trial_started_at bigint,
  free_since_at bigint,
  wxweb_openid text,
  wxapp_openid text,
  wechat_unionid text,
  wechat_nickname text,
  wechat_avatar text,
  last_login_at bigint,
  apple_sub text,
  apple_email text,
  apple_full_name text,
  purchased_credits integer NOT NULL DEFAULT 0,
  bonus_carried integer NOT NULL DEFAULT 0,
  bonus_current integer NOT NULL DEFAULT 0
);

CREATE TABLE hosts (
  id text PRIMARY KEY,
  owner_id bigint NOT NULL REFERENCES users(id),
  name text NOT NULL,
  token_hash text UNIQUE NOT NULL,
  e2ee_public_key text,
  node_id text,
  online smallint NOT NULL DEFAULT 0,
  created_at text NOT NULL
);

CREATE TABLE refresh_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id),
  token_hash text UNIQUE NOT NULL,
  expires_at bigint NOT NULL,
  revoked smallint NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);

CREATE TABLE join_tokens (
  id text PRIMARY KEY,
  label text,
  owner_id bigint NOT NULL REFERENCES users(id),
  token_hash text UNIQUE NOT NULL,
  expires_at bigint NOT NULL,
  revoked smallint NOT NULL DEFAULT 0,
  created_at text NOT NULL
);

CREATE TABLE bind_sessions (
  id text PRIMARY KEY,
  consume_token_hash text UNIQUE NOT NULL,
  e2ee_public_key text,
  name text,
  owner_id bigint REFERENCES users(id),
  status text NOT NULL DEFAULT 'pending',
  created_at text NOT NULL,
  expires_at bigint NOT NULL
);

CREATE TABLE host_share (
  host_id text NOT NULL REFERENCES hosts(id),
  user_id bigint NOT NULL REFERENCES users(id),
  role text NOT NULL DEFAULT 'member',
  created_at text NOT NULL,
  PRIMARY KEY (host_id, user_id)
);

CREATE TABLE audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint,
  event text NOT NULL,
  detail_json text NOT NULL DEFAULT '{}',
  ip text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT 'user',
  actor_user_id bigint,
  created_at bigint NOT NULL
);

CREATE TABLE email_codes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  email text NOT NULL,
  purpose text NOT NULL,
  code_hash text NOT NULL,
  expires_at bigint NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);

CREATE TABLE sms_codes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  phone text NOT NULL,
  purpose text NOT NULL,
  code_hash text NOT NULL,
  expires_at bigint NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);

CREATE TABLE subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id),
  plan_id text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  started_at bigint NOT NULL,
  expires_at bigint NOT NULL,
  created_at bigint NOT NULL,
  channel text,
  subscription_id text,
  will_renew smallint NOT NULL DEFAULT 0
);

CREATE TABLE orders (
  id text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id),
  plan_id text NOT NULL,
  amount_cny double precision NOT NULL,
  status text NOT NULL DEFAULT 'created',
  channel text,
  out_id text,
  ticket text,
  payment_id text,
  created_at bigint NOT NULL,
  paid_at bigint
);

CREATE TABLE payments (
  id text PRIMARY KEY,
  order_id text NOT NULL REFERENCES orders(id),
  user_id bigint NOT NULL REFERENCES users(id),
  channel text NOT NULL,
  channel_order_id text NOT NULL,
  amount_cny double precision NOT NULL,
  paid_at bigint NOT NULL,
  raw text NOT NULL DEFAULT '{}'
);

CREATE TABLE credits_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id),
  delta integer NOT NULL,
  bucket text NOT NULL,
  reason text NOT NULL,
  source_type text,
  source_id text,
  idempotency_key text UNIQUE,
  balance_after bigint,
  created_at bigint NOT NULL
);

CREATE TABLE meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE apple_tokens (
  user_id bigint PRIMARY KEY REFERENCES users(id),
  refresh_token text,
  access_token text,
  updated_at bigint NOT NULL DEFAULT 0
);

CREATE TABLE usage_daily (
  user_id bigint NOT NULL REFERENCES users(id),
  host_id text NOT NULL DEFAULT '',
  date text NOT NULL,
  instance_id text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT '',
  relay_seconds integer NOT NULL DEFAULT 0,
  relay_bytes_up integer NOT NULL DEFAULT 0,
  relay_bytes_down integer NOT NULL DEFAULT 0,
  direct_bytes_up integer NOT NULL DEFAULT 0,
  direct_bytes_down integer NOT NULL DEFAULT 0,
  cloud_asr_seconds integer NOT NULL DEFAULT 0,
  local_asr_seconds integer NOT NULL DEFAULT 0,
  cloud_tts_chars integer NOT NULL DEFAULT 0,
  local_tts_chars integer NOT NULL DEFAULT 0,
  sessions integer NOT NULL DEFAULT 0,
  updated_at bigint NOT NULL,
  PRIMARY KEY (user_id, host_id, date, instance_id)
) PARTITION BY RANGE (date);

CREATE TABLE usage_daily_default PARTITION OF usage_daily DEFAULT;

CREATE TABLE nodes (
  id text PRIMARY KEY,
  name text NOT NULL,
  advertise_url text NOT NULL,
  token_hash text UNIQUE NOT NULL,
  region text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'online',
  enabled smallint NOT NULL DEFAULT 1,
  last_ip text,
  capacity integer NOT NULL DEFAULT 0,
  weight integer NOT NULL DEFAULT 100,
  last_heartbeat bigint NOT NULL DEFAULT 0,
  connections integer NOT NULL DEFAULT 0,
  active_streams integer NOT NULL DEFAULT 0,
  bytes_in integer NOT NULL DEFAULT 0,
  bytes_out integer NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);

CREATE TABLE node_metrics (
  node_id text NOT NULL,
  ts bigint NOT NULL,
  connections integer NOT NULL DEFAULT 0,
  active_streams integer NOT NULL DEFAULT 0,
  bytes_in integer NOT NULL DEFAULT 0,
  bytes_out integer NOT NULL DEFAULT 0,
  PRIMARY KEY (node_id, ts)
);

CREATE TABLE relay_join_tokens (
  id text PRIMARY KEY,
  name text NOT NULL,
  token_hash text UNIQUE NOT NULL,
  token_plaintext text NOT NULL,
  created_by bigint NOT NULL,
  created_at bigint NOT NULL,
  revoked_at bigint
);

CREATE TABLE relay_join_events (
  id text PRIMARY KEY,
  token_id text NOT NULL,
  node_id text NOT NULL,
  src_ip text,
  at bigint NOT NULL
);

-- Partial/unique indexes mirroring SQLite (SQLite ALTER ADD COLUMN can't carry UNIQUE, so they are separate indexes).
CREATE UNIQUE INDEX idx_users_email ON users(email);
CREATE UNIQUE INDEX idx_users_phone ON users(phone);
CREATE UNIQUE INDEX idx_users_wxweb_openid ON users(wxweb_openid);
CREATE UNIQUE INDEX idx_users_wxapp_openid ON users(wxapp_openid);
CREATE UNIQUE INDEX idx_users_wechat_unionid ON users(wechat_unionid);
CREATE UNIQUE INDEX idx_users_apple_sub ON users(apple_sub);
CREATE INDEX idx_usage_daily_host ON usage_daily(host_id, date);
CREATE INDEX idx_hosts_node ON hosts(node_id);
