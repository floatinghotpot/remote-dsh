-- 0017: analytics events (57-retention-analytics, Phase 2).
-- Client-side product events (app_open / purchase_start) for DAU / retention /
-- purchase funnel. event_id is unique for idempotent client retries
-- (ON CONFLICT DO NOTHING on insert).
CREATE TABLE IF NOT EXISTS analytics_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event text NOT NULL,
  user_id bigint,
  device_id text NOT NULL,
  ts bigint NOT NULL,
  props text NOT NULL DEFAULT '{}',
  event_id text UNIQUE NOT NULL,
  created_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_analytics_events_ts ON analytics_events(ts);
CREATE INDEX IF NOT EXISTS idx_analytics_events_user ON analytics_events(user_id);
CREATE INDEX IF NOT EXISTS idx_analytics_events_event ON analytics_events(event, ts);
